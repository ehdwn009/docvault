// 독자용 문장에서 AI의 작업 사정을 걷어 낸다 — 실제 회차에서 요약 13~16건에 "제공된 글에는 상세 내용이 없다",
// "제목만으로는 확인되지 않는다"가 그대로 실렸다 (설계 "④ 요약", 사용성 평가 2026-10-01).
// 지시로 먼저 막고, 그래도 새어 나온 것을 여기서 지운다. 뉴스 자체의 "원인은 아직 알 수 없다"는 남기도록
// 주어진 글·제목·발췌를 가리키는 말이 함께 있을 때만 잡는다

const META = new RegExp(
  [
    '(제공된|주어진)\\s*(글|기사|내용|정보|자료|텍스트|발췌)',
    '제목만으로는',
    '(글|기사|발췌|본문|원문)(에는|에서는|만으로는)[^.。]*?(나와 있지 않|확인되지 않|언급되지 않|드러나지 않|알 수 없|없다|없음)',
    '세부\\s*(내용|사항)[은는이가]?\\s*(제공|나와 있지|확인되지|알려지지)',
  ].join('|'),
);

/** 문장 단위로 걸러 남은 문장만 잇는다. 다 걸리면 빈 문자열 */
export function stripMeta(text: string): string {
  if (!META.test(text)) return text.trim();
  return text
    .split(/(?<=[.!?。])\s+/)
    .filter((s) => !META.test(s))
    .join(' ')
    .trim();
}

/** 지시문: 선별(참고 기사)·요약 프롬프트에 같은 말로 넣는다 */
export const NO_META_RULE =
  "- 근거가 부족하다는 사정('제공된 글에는 …이 없다', '제목만으로는 알 수 없다')을 독자용 문장에 쓰지 않는다. 쓸 것이 없으면 짧게 쓰거나 빈 문자열로 둔다.";
